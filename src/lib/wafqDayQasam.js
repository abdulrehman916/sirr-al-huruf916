// The day's qasam, written round the square as its tawkeel.
//
// Kashf al-Haqa'iq, pp. 29-31 (the second set of day qasams, which the
// book calls "more precise and better, because it gathers the ayah, the
// angel, the khadims set over it, the letters and the names"). Each day's
// qasam names that day's khadim, its letter group, the angel set over it,
// a verse of the Fatiha, names of Allah and a -هطهطيل name, and ends with
// "...وتتوكل بعملي كذا وكذا" — so it is itself a tawkeel, a charge.
//
// After it the book's command to the khadims once the square is filled
// (p. 301): "اقسم عليكم يا خدام هذه الأسماء أن تفعلوا لي كذا وكذا (تذكر
// حاجتك)". For love the book's own words written round the wafq (pp.
// 50-51): the ayahs, then "توكلوا يا خدام هذه الآيات بتهييج فلان بن
// فلانة ...". In each, only كذا وكذا / فلان بن فلانة is filled in.
//
// The common azima (p. 31) is read after the day's qasam on every work,
// with the day's incense; the book says it is "read or written".
//
// Counts (p. 24-25): the qasam is said as many times as the total, or the
// number of houses on a side, or the number of letters; the azima three
// times at least, five in the middle, seven at most.
//
// Each text is kept twice: `p` as the book prints it (for the ring) and
// `v` with harakat (for reading). The khadim names, letter groups and
// -هطهطيل names are left as printed, without harakat, since the book
// gives none.
// ═══════════════════════════════════════════════════════════════

