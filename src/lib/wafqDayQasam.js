/** "فلان بن فلانة" — بن for a man, بنت for a woman. */
export function personAr(name, mother, female = false) {
  const a = (name || "").trim(), m = (mother || "").trim();
  if (!a) return "";
  return m ? `${a} ${female ? "بنت" : "بن"} ${m}` : a;
}

