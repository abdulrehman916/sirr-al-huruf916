const PH = "كذا وكذا";
const at = (pair, voc) => pair[voc ? 1 : 0];

/** The day's qasam with the need in the place of كذا وكذا. */
export function dayQasam(wd, need, { voc = false } = {}) {
  const q = DAY_QASAM[((wd % 7) + 7) % 7];
  const x = (need || "").trim() || PH;
  return [at(q.open, voc), at(q.mid, voc), at(q.end, voc), x, at(q.tail, voc)]
    .filter(Boolean).join(" ");
}

/** p. 301 — the command to the square's khadims once it is filled. */
export function khadimCommand(need, { voc = false } = {}) {
  const x = (need || "").trim() || PH;
  return voc
    ? `أُقْسِمُ عَلَيْكُمْ يَا خُدَّامَ هَٰذِهِ الْأَسْمَاءِ أَنْ تَفْعَلُوا لِي ${x}`
    : `أقسم عليكم يا خدام هذه الأسماء أن تفعلوا لي ${x}`;
}

/** pp. 50-51 — the love ayahs written round the wafq, then their tawkeel. */
