/** Fill a preset phrase with the people. */
export function fillNeed(tpl, person, other = "", female = false) {
  return (tpl || "")
    .replaceAll("{p}", person || "فلان بن فلانة")
    .replaceAll("{s}", other || "فلانة بنت فلانة")
    .replaceAll("{h}", female ? "ها" : "ه")
    .replace(/\s+/g, " ").trim();
}
