export function loveTawkeel(sought, { voc = false } = {}) {
  const x = (sought || "").trim() || "فلان بن فلانة";
  return voc
    ? `تَوَكَّلُوا يَا خُدَّامَ هَٰذِهِ الْآيَاتِ بِتَهْيِيجِ ${x} بِحَقِّ تَسْبِيحِ الْمَلَائِكَةِ وَصَلَاةِ الشُّهَدَاءِ فَسَوْفَ يَأْتِي اللَّهُ بِقَوْمٍ يُحِبُّهُمْ وَيُحِبُّونَهُ وَأَلْقَيْتُ عَلَيْكَ مَحَبَّةً مِنِّي وَاذْكُرُوا نِعْمَةَ اللَّهِ عَلَيْكُمْ إِلَى قُلُوبِكُمْ وَنَزَعْنَا مَا فِي صُدُورِهِمْ مِنْ غِلٍّ`
    : `توكلوا يا خدام هذه الآيات بتهييج ${x} بحق تسبيح الملائكة وصلاة الشهداء فسوف يأتي الله بقوم يحبهم ويحبونه وألقيت عليك محبة مني واذكروا نعمة الله عليكم إلى قلوبكم ونزعنا ما في صدورهم من غل`;
}

/**
 * The whole text for the ring: the day's qasam with the need, then the
 * command. For love the command is the book's love tawkeel, preceded by
 * the love ayahs it refers to ("خدام هذه الآيات").
 */
export function tawkeelRing(wd, need, { love = false, sought = "" } = {}) {
  const q = dayQasam(wd, need);
  return love
    ? [q, ...LOVE_AYAHS, loveTawkeel(sought)].join(" ")
    : [q, khadimCommand(need)].join(" ");
}

